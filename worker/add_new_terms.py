def slugify(text):
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c))
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = re.sub(r"-+", "-", text).strip("-")
    return text[:60]


def translate(el_text):
    body = json.dumps({"term": el_text, "sourceLang": "el"}).encode("utf-8")
    req = urllib.request.Request(WORKER, data=body, method="POST", headers={
        "Content-Type": "application/json",
        "Origin": "https://i-talk.gr",
        "User-Agent": UA
    })
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode("utf-8"))


def main():
    with open(TERMS, "r", encoding="utf-8") as f:
        data = json.load(f)

    existing_ids = {t["id"] for t in data["terms"]}
    existing_el = {t["translations"].get("el", "").strip().lower() for t in data["terms"]}
    added = 0
    skipped = 0
    failed = []

    total = sum(len(v) for v in SEED.values())
    counter = 0
    for cat, seeds in SEED.items():
        for greek in seeds:
            counter += 1
            # Skip if this exact Greek phrase is already in terms
            if greek.strip().lower() in existing_el:
                print(f"  [{counter}/{total}] SKIP (exists) {greek}")
                skipped += 1
                continue
            print(f"  [{counter}/{total}] [{cat}] {greek} …")
            try:
                resp = translate(greek)
            except Exception as e:
                print(f"    ERR: {e}")
                failed.append(greek)
                time.sleep(1.0)
                continue

            if not resp.get("translations"):
                print(f"    no translations: {resp.get('note') or resp.get('error')}")
                failed.append(greek)
                continue

            en = (resp["translations"].get("en") or "").strip()
            # Base slug on English translation for readability
            base = slugify(en) or slugify(greek) or f"{cat}-{counter}"
            slug = base
            n = 2
            while slug in existing_ids:
                slug = f"{base}-{n}"
                n += 1

            new_term = {
                "id": slug,
                "category": cat,
                "translations": {
                    lang: (resp["translations"].get(lang) or "").strip()
                    for lang in ["el", "en", "ar", "fa", "fr"]
                },
                "definition_el": (resp.get("definition_el") or "").strip(),
                "definition_en": (resp.get("definition_en") or "").strip(),
                "sources": [f"AI-generated ({resp.get('model')}) 2026-09-06 — needs native review"]
            }
            data["terms"].append(new_term)
            existing_ids.add(slug)
            existing_el.add(greek.strip().lower())
            added += 1
            time.sleep(0.35)

    data["meta"]["version"] = "0.4.0"
    data["meta"]["updated"] = "2026-09-06"

    with open(TERMS, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print()
    print(f"added:   {added}")
    print(f"skipped: {skipped}")
    print(f"failed:  {len(failed)}")
    print(f"total terms now: {len(data['terms'])}")
    if failed:
        print("failed terms:")
        for g in failed[:20]:
            print(f"  - {g}")


if __name__ == "__main__":
    main()
